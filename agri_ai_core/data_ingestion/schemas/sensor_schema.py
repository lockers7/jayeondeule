# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# sensor_schema 모듈
# 모듈 기능에 대한 설명이 필요합니다.
# --->
# [클래스] SensorReading: 센서 읽기 데이터
# [클래스] SensorData: 센서 데이터 전체 모델
# [클래스] OptimalCondition: 최적 환경 조건
# [클래스] Config: 기능 설명 필요
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
from pydantic import BaseModel, Field
from typing import Optional
from datetime import datetime


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 센서 읽기 데이터
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class SensorReading(BaseModel):
    indoor_temperature: Optional[float] = Field(None, description="내부온도 (℃)")
    indoor_humidity: Optional[float] = Field(None, description="내부습도 (%)")
    outdoor_temperature: Optional[float] = Field(None, description="외부온도 (℃)")
    outdoor_humidity: Optional[float] = Field(None, description="외부습도 (%)")
    co2: Optional[float] = Field(None, description="CO2 농도 (ppm)")
    water_temperature: Optional[float] = Field(None, description="수온 (℃)")
    light_level: Optional[float] = Field(None, description="광량")
    water_level: Optional[float] = Field(None, description="수위")


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 센서 데이터 전체 모델
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class SensorData(BaseModel):
    farm_id: int = Field(..., description="농장 ID")
    house_id: int = Field(..., description="재배사 ID")
    record_datetime: datetime = Field(..., description="기록 일시")
    readings: SensorReading = Field(..., description="센서 읽기값")
    is_manual: bool = Field(False, description="수동 설정 여부")

    class Config:
        json_encoders = {
            datetime: lambda v: v.strftime("%Y-%m-%d %H:%M:%S")
        }


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 최적 환경 조건
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class OptimalCondition(BaseModel):
    temperature_min: float = Field(..., description="온도 최저")
    temperature_optimal: float = Field(..., description="온도 적정")
    temperature_max: float = Field(..., description="온도 최고")
    humidity_min: float = Field(..., description="습도 최저")
    humidity_optimal: float = Field(..., description="습도 적정")
    humidity_max: float = Field(..., description="습도 최고")
    co2_min: float = Field(..., description="CO2 최저")
    co2_optimal: float = Field(..., description="CO2 적정")
    co2_max: float = Field(..., description="CO2 최고")
    water_temp_min: float = Field(..., description="수온 최저")
    water_temp_optimal: float = Field(..., description="수온 적정")
    water_temp_max: float = Field(..., description="수온 최고")
