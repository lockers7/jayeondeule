# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# relay_schema 모듈
# 모듈 기능에 대한 설명이 필요합니다.
# --->
# [클래스] RelaySettings: 릴레이 설정
# [클래스] RelayData: 릴레이 데이터 전체 모델
# [클래스] EnvironmentAssessment: 환경 평가
# [클래스] ControlPlan: 제어 계획
# [클래스] Config: 기능 설명 필요
# validate_safety_rules: 기능 설명 필요
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
from pydantic import BaseModel, Field, field_validator
from typing import Optional, List
from datetime import datetime


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 릴레이 설정
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class RelaySettings(BaseModel):
    water_heater: bool = Field(False, description="수온히터")
    fog_motor: bool = Field(False, description="습도모터")
    drainage_valve: bool = Field(False, description="배수밸브")
    intake_fan: bool = Field(False, description="흡입모터")
    exhaust_fan: bool = Field(False, description="배출모터")
    lighting: bool = Field(False, description="조명토글")
    irrigation: bool = Field(False, description="관수토글")
    indoor_heater: bool = Field(False, description="내부히터")
    circulation_valve: bool = Field(False, description="순환밸브")
    intake_valve: bool = Field(False, description="흡입밸브")
    exhaust_valve: bool = Field(False, description="배출밸브")
    heater_valve: bool = Field(False, description="히터밸브")


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 릴레이 데이터 전체 모델
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class RelayData(BaseModel):
    farm_id: int = Field(..., description="농장 ID")
    house_id: int = Field(..., description="재배사 ID")
    record_datetime: datetime = Field(..., description="기록 일시")
    settings: RelaySettings = Field(..., description="릴레이 설정")

    class Config:
        json_encoders = {
            datetime: lambda v: v.strftime("%Y-%m-%d %H:%M:%S")
        }


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 환경 평가
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class EnvironmentAssessment(BaseModel):
    indoor_temp: Optional[float] = Field(None, description="내부온도")
    humidity: Optional[float] = Field(None, description="습도")
    co2: Optional[float] = Field(None, description="CO2")
    water_temp: Optional[float] = Field(None, description="수온")
    status_summary: Optional[str] = Field(None, description="상태 요약")


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 제어 계획
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class ControlPlan(BaseModel):
    house_id: int = Field(..., description="재배사 ID")
    timestamp: str = Field(..., description="타임스탬프")
    environment_assessment: EnvironmentAssessment = Field(..., description="환경 평가")
    air_circulation_mode: Optional[str] = Field(None, description="공기순환 모드")
    relay_settings: RelaySettings = Field(..., description="릴레이 설정")
    safety_rule_checks: List[str] = Field(default_factory=list, description="안전 규칙 체크")
    reason: str = Field(..., max_length=300, description="제어 이유")

    @field_validator('safety_rule_checks')
    @classmethod
    def validate_safety_rules(cls, v):
        if not v or len(v) == 0:
            raise ValueError("안전 규칙 체크는 최소 1개 이상이어야 합니다")
        return v
