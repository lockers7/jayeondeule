# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# JSON 데이터 내보내기 모듈
# 시스템 데이터를 JSON 형식으로 내보내어 백업하거나
# 외부 시스템과 데이터를 공유할 수 있도록 합니다.
# --->
# get_json_cache_dir: JSON 캐시 디렉토리 경로 반환 (없으면 생성)
# get_training_json_path: 학습용 JSON 파일 경로 반환
# get_units_json_path: Units JSON 파일 경로 반환
# get_crops_json_path: Crops JSON 파일 경로 반환
# export_units_to_json: 특정 농장/재배사의 Units 데이터를 JSON으로 내보내기
# export_crops_to_json: 특정 농장/재배사의 Crops 데이터를 JSON으로 내보내기
# run_data_export: 모든 농장/재배사의 데이터를 JSON으로 내보내기
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
import os
import json
from datetime import datetime

from agri_ai_core.log_utils.log_handlers import setup_logger
from agri_ai_core.shared_modules.config.settings import settings
from agri_ai_core.data_ingestion.postgres_reader import (
    read_farm_house_list,
    read_units_data,
    read_crops_data,
    update_last_get_time
)

logger = setup_logger(__name__)


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# JSON 캐시 디렉토리 반환
# --->
# JSON 캐시 디렉토리 경로 반환 (없으면 생성)
# Returns:
# str: 디렉토리 경로
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def get_json_cache_dir():
    cache_path = settings.vector.vector_cache or ""
    cache_dir = os.path.dirname(cache_path)
    if cache_dir and not os.path.exists(cache_dir):
        os.makedirs(cache_dir)
        logger.info(f"JSON 캐시 디렉토리 생성: {cache_dir}")

    if cache_dir and not cache_dir.endswith('/'):
        cache_dir = cache_dir + '/'
    return cache_dir


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 학습용 JSON 데이터 경로
# --->
# 학습용 JSON 파일 경로 반환
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def get_training_json_path():
    filename = settings.house_source_json or ""
    return (get_json_cache_dir() or "") + filename


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# Units JSON 데이터 경로
# --->
# Units JSON 파일 경로 반환
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def get_units_json_path():
    filename = settings.units_temp_json or ""
    return (get_json_cache_dir() or "") + filename


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# Crops JSON 데이터 경로
# --->
# Crops JSON 파일 경로 반환
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def get_crops_json_path():
    filename = settings.crops_temp_json or ""
    return (get_json_cache_dir() or "") + filename


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# Units 데이터 JSON 내보내기
# --->
# 특정 농장/재배사의 Units 데이터를 JSON으로 내보내기
# Args:
# farm_id: 농장 ID
# house_id: 재배사 ID
# output_path: 출력 파일 경로 (선택)
# Returns:
# bool: 성공 여부
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def export_units_to_json(farm_id, house_id, output_path=None):
    try:
        units_data = read_units_data(farm_id, house_id)

        if output_path is None:
            output_path = get_units_json_path()

        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(units_data, f, ensure_ascii=False, indent=4, default=str)

        logger.info(f"Units 데이터 JSON 내보내기 완료: {output_path}")
        return True
    except Exception as e:
        logger.error(f"Units 데이터 JSON 내보내기 오류: {str(e)}")
        return False


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# Crops 데이터 JSON 내보내기
# --->
# 특정 농장/재배사의 Crops 데이터를 JSON으로 내보내기
# Args:
# farm_id: 농장 ID
# house_id: 재배사 ID
# output_path: 출력 파일 경로 (선택)
# Returns:
# bool: 성공 여부
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def export_crops_to_json(farm_id, house_id, output_path=None):
    try:
        crops_data = read_crops_data(farm_id, house_id)

        if output_path is None:
            output_path = get_crops_json_path()

        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(crops_data, f, ensure_ascii=False, indent=4, default=str)

        logger.info(f"Crops 데이터 JSON 내보내기 완료: {output_path}")
        return True
    except Exception as e:
        logger.error(f"Crops 데이터 JSON 내보내기 오류: {str(e)}")
        return False


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 전체 데이터 내보내기 실행
# --->
# 모든 농장/재배사의 데이터를 JSON으로 내보내기
# Returns:
# bool: 성공 여부
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def run_data_export():
    try:
        set_json = []
        latest_get_time = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        farmhouses = read_farm_house_list()
        if not farmhouses:
            logger.warning("농장-재배사 목록이 비어있습니다.")
            return False

        for fh in farmhouses:
            farm_id = fh['farm_id']
            farm_name = fh['farm_name']
            house_id = fh['hous_id']
            house_name = fh['hous_name']

            units_rst = read_units_data(farm_id, house_id)
            crops_rst = read_crops_data(farm_id, house_id)

            set_json.append({
                'farm_id': farm_id,
                'farm_name': farm_name,
                'house_id': house_id,
                'house_name': house_name,
                'units': units_rst,
                'crops': crops_rst,
                'create_datetime': latest_get_time
            })

            update_last_get_time(farm_id, house_id, latest_get_time)

        # JSON 파일 저장
        json_source_file = get_training_json_path()
        with open(json_source_file, 'w', encoding='utf-8') as wf:
            json.dump(set_json, wf, ensure_ascii=False, indent=4, default=str)

        unit_total_count = sum(len(item.get("units", [])) for item in set_json)
        crop_total_count = sum(len(item.get("crops", [])) for item in set_json)
        logger.info(f"농장 운용 기본정보 저장완료 - 장치정보: {unit_total_count}건, 생육정보: {crop_total_count}건")

        return True

    except Exception as e:
        import traceback
        logger.error(f"농장 운용정보 생성 및 JSON 저장 중 오류: {str(e)}")
        logger.error(f"스택 트레이스: {traceback.format_exc()}")
        return False


# 기존 함수명 호환성
pgdb_to_json = run_data_export
