# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 설정 관리 모듈
# 환경 변수, 설정 파일을 읽어와 시스템 전체에서 사용하는
# 설정값을 중앙화하여 관리하는 싱글톤 객체를 제공합니다.
# --->
# [클래스] DatabaseSettings: PostgreSQL 연결 파라미터
# [클래스] VectorStoreSettings: ChromaDB 설정
# [클래스] ModelSettings: LLM 모델 파라미터
# [클래스] CollectionSettings: ChromaDB 컬렉션명
# [클래스] LoggingSettings: 로그 설정
# [클래스] AppSettings: 통합 애플리케이션 설정
# get_settings: 환경변수에서 설정을 로드하여 AppSettings 객체 반환
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
import os
from dataclasses import dataclass
from functools import lru_cache
from typing import Optional

from dotenv import load_dotenv


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 데이터베이스 설정
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@dataclass(frozen=True)
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# PostgreSQL 연결 파라미터
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class DatabaseSettings:
    host: str
    port: int
    database: str
    user: str
    password: str


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 벡터 저장소 설정
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@dataclass(frozen=True)
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# ChromaDB 설정
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class VectorStoreSettings:
    client_type: str
    backend: Optional[str]
    db_path: Optional[str]
    http_host: Optional[str]
    http_port: Optional[int]
    vector_db: Optional[str]
    vector_cache: Optional[str]


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 모델 설정
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@dataclass(frozen=True)
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# LLM 모델 파라미터
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class ModelSettings:
    name: str
    prefix: Optional[str]
    units_name: Optional[str]


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 컬렉션 설정
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@dataclass(frozen=True)
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# ChromaDB 컬렉션명
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class CollectionSettings:
    farm: Optional[str]
    source: Optional[str]
    stats: Optional[str]
    optimal: Optional[str]
    learned: Optional[str]
    setting: Optional[str]
    docs_learned: Optional[str]
    last_learned: Optional[str]
    self_learned: Optional[str]
    pattern_learned: Optional[str]


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 로깅 설정
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@dataclass(frozen=True)
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 로그 설정
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class LoggingSettings:
    path: Optional[str]
    level: Optional[str]


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 앱 설정
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@dataclass(frozen=True)
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 통합 애플리케이션 설정
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class AppSettings:
    corps_name: Optional[str]
    house_source_json: Optional[str]
    units_temp_json: Optional[str]
    crops_temp_json: Optional[str]
    embedding_dim: int
    database: DatabaseSettings
    vector: VectorStoreSettings
    model: ModelSettings
    collections: CollectionSettings
    logging: LoggingSettings


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 유틸리티 함수
# --->
# 문자열을 정수로 변환
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def _get_int(value: Optional[str], default: Optional[int] = None) -> Optional[int]:
    if value is None:
        return default
    try:
        return int(value)
    except ValueError:
        return default


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 설정 로더
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@lru_cache()
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 환경변수에서 설정을 로드하여 AppSettings 객체 반환
# --->
# 캐시되어 한 번만 로드됨
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def get_settings() -> AppSettings:
    load_dotenv(override=True)

    database = DatabaseSettings(
        host=os.getenv("PGDB_HOST", "127.0.0.1"),
        port=_get_int(os.getenv("PGDB_PORT"), 5432),
        database=os.getenv("PGDB_DATABASE", ""),
        user=os.getenv("PGDB_USER", ""),
        password=os.getenv("PGDB_PASSWORD", ""),
    )

    vector = VectorStoreSettings(
        client_type=os.getenv("CLIENT_TYPE", ""),
        backend=os.getenv("CHROMADB_BACKEND"),
        db_path=os.getenv("CHROMA_DB_PATH"),
        http_host=os.getenv("CHROMA_DB_HTTP_HOST"),
        http_port=_get_int(os.getenv("CHROMA_DB_HTTP_PORT")),
        vector_db=os.getenv("VECTOR_DB"),
        vector_cache=os.getenv("VECTOR_CACHE"),
    )

    model = ModelSettings(
        name=os.getenv("MODEL_NAME", ""),
        prefix=os.getenv("MODEL_PREFIX"),
        units_name=os.getenv("UNITS_NAME"),
    )

    collections = CollectionSettings(
        farm=os.getenv("COLLECTION_FARM"),
        source=os.getenv("COLLECTION_SOURCE"),
        stats=os.getenv("COLLECTION_STATS"),
        optimal=os.getenv("COLLECTION_OPTIMAL"),
        learned=os.getenv("COLLECTION_LEARNED"),
        setting=os.getenv("COLLECTION_SETTING"),
        docs_learned=os.getenv("COLLECTION_DOCS_LEARNED"),
        last_learned=os.getenv("COLLECTION_LAST_LEARNED"),
        self_learned=os.getenv("COLLECTION_SELF_LEARNED"),
        pattern_learned=os.getenv("COLLECTION_PATTERN_LEARNED"),
    )

    logging = LoggingSettings(
        path=os.getenv("LOG_PATH"),
        level=os.getenv("LOG_LEVEL", "INFO"),
    )

    return AppSettings(
        corps_name=os.getenv("CORPS_NAME"),
        house_source_json=os.getenv("HOUSE_SOURCE_JSON"),
        units_temp_json=os.getenv("UNITS_TEMP_JSON"),
        crops_temp_json=os.getenv("CROPS_TEMP_JSON"),
        embedding_dim=_get_int(os.getenv("CHROMA_EMBEDDING_DIM"), 1024) or 1024,
        database=database,
        vector=vector,
        model=model,
        collections=collections,
        logging=logging,
    )


# 전역 설정 인스턴스
settings = get_settings()
