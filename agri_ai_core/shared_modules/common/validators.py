# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 데이터 검증 모듈
# 입력 데이터의 유효성을 검사하는 다양한 검증 함수를 제공하며,
# 데이터 무결성을 보장합니다.
# --->
# clean_sensor_value: 센서 값을 float로 정리/변환
# parse_boolean: 다양한 형태의 값을 불리언으로 변환
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
import re
from decimal import Decimal


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 센서 값을 정리하고 변환하는 유틸리티 함수
# --->
# 센서 값을 float로 정리/변환
# Args:
# value: 변환할 값 (int, float, Decimal, str 등)
# Returns:
# float: 정리된 센서 값 (소수점 2자리)
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def clean_sensor_value(value):
    try:
        if value is None:
            return 0.0

        if isinstance(value, (int, float, Decimal)):
            return round(float(value), 2)

        if isinstance(value, str):
            value = value.strip()
            if not value:
                return 0.0

            match = re.search(r"[-+]?[0-9]*\.?[0-9]+", value)
            if match:
                return round(float(match.group()), 2)

        return round(float(value), 2)
    except Exception:
        return 0.0


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 다양한 형태의 값을 불리언으로 변환하는 유틸리티 함수
# --->
# 다양한 형태의 값을 불리언으로 변환
# Args:
# value: 변환할 값 (bool, int, float, str 등)
# Returns:
# bool: 변환된 불리언 값
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def parse_boolean(value):
    if value is None:
        return False

    if isinstance(value, bool):
        return value

    if isinstance(value, (int, float)):
        return bool(value)

    if isinstance(value, str):
        return value.lower() in ('true', 't', 'yes', 'y', '1')

    return False


