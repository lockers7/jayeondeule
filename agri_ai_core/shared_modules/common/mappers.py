# 릴레이 키에 대한 이름 반환
# --->
# 릴레이 키(영문)를 사용자 친화적인 이름으로 변환
# Args:
# relay_key: 릴레이 키 (예: water_heater_flag)
# house_id: 재배사 ID (E버전 구분용)
# default: 기본 반환 값
# Returns:
# str: 릴레이 표시 이름
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def get_relay_name(relay_key, house_id=None, default=None):
    mapping = get_relay_mapping(house_id)
    entry = mapping.get(relay_key)

    if isinstance(entry, (list, tuple)) and entry:
        if len(entry) > 1 and entry[1]:
            return entry[1]
        return entry[0]

    return default or relay_key


