# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 유틸리티 함수
# --->
# 문자열을 정수로 변환
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def _get_int(value: Optional[str], default: Optional[int] = None) -> Optional[int]:
    if value is None:
        return default
    try:
        return int(value)
    except ValueError:
        return default


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 설정 로더
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@lru_cache()
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 환경변수에서 설정을 로드하여 AppSettings 객체 반환
# --->
# 캐시되어 한 번만 로드됨
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def get_settings() -> AppSettings:
    load_dotenv(override=True)

    database = DatabaseSettings(
        host=os.getenv("PGDB_HOST", "127.0.0.1"),
        port=_get_int(os.getenv("PGDB_PORT"), 5432),
        database=os.getenv("PGDB_DATABASE", ""),
        user=os.getenv("PGDB_USER", ""),
        password=os.getenv("PGDB_PASSWORD", ""),
    )

    vector = VectorStoreSettings(
        client_type=os.getenv("CLIENT_TYPE", ""),
        backend=os.getenv("CHROMADB_BACKEND"),
        db_path=os.getenv("CHROMA_DB_PATH"),
        http_host=os.getenv("CHROMA_DB_HTTP_HOST"),
        http_port=_get_int(os.getenv("CHROMA_DB_HTTP_PORT")),
        vector_db=os.getenv("VECTOR_DB"),
        vector_cache=os.getenv("VECTOR_CACHE"),
    )

    model = ModelSettings(
        name=os.getenv("MODEL_NAME", ""),
        prefix=os.getenv("MODEL_PREFIX"),
        units_name=os.getenv("UNITS_NAME"),
    )

    collections = CollectionSettings(
        farm=os.getenv("COLLECTION_FARM"),
        source=os.getenv("COLLECTION_SOURCE"),
        stats=os.getenv("COLLECTION_STATS"),
        optimal=os.getenv("COLLECTION_OPTIMAL"),
        learned=os.getenv("COLLECTION_LEARNED"),
        setting=os.getenv("COLLECTION_SETTING"),
        docs_learned=os.getenv("COLLECTION_DOCS_LEARNED"),
        last_learned=os.getenv("COLLECTION_LAST_LEARNED"),
        self_learned=os.getenv("COLLECTION_SELF_LEARNED"),
        pattern_learned=os.getenv("COLLECTION_PATTERN_LEARNED"),
    )

    logging = LoggingSettings(
        path=os.getenv("LOG_PATH"),
        level=os.getenv("LOG_LEVEL", "INFO"),
    )

    return AppSettings(
        corps_name=os.getenv("CORPS_NAME"),
        house_source_json=os.getenv("HOUSE_SOURCE_JSON"),
        units_temp_json=os.getenv("UNITS_TEMP_JSON"),
        crops_temp_json=os.getenv("CROPS_TEMP_JSON"),
        embedding_dim=_get_int(os.getenv("CHROMA_EMBEDDING_DIM"), 1024) or 1024,
        database=database,
        vector=vector,
        model=model,
        collections=collections,
        logging=logging,
    )


# 전역 설정 인스턴스
