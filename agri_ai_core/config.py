# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 릴레이 맵핑정보 검색
# return_type (str): 반환할 정보 타입
#     - 'english_name': 영문명 반환 (relay_로 시작하는 키 우선)
#     - 'relay_name': 릴레이명 반환 (relay_로 시작하는 키 우선)
#     - 'function_detail': 기능상세 반환 (index 0)
#     - 'function_name': 기능명 반환 (index 1)
#     - 'function_content': 기능내용 반환 (index 2)
# --->
# 릴레이 기능 검색
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def search_relay_function(search_item, search_type, search_value, return_type):
    if search_item == 'rfm':
        mapping = RELAY_FIELD_MAPPING
    elif search_item == 'rfm_e':
        mapping = RELAY_FIELD_MAPPING_E
    else:
        return None

    if search_type == 'function_name':
        search_index = 1
    elif search_type == 'relay_name':
        search_index = None
    else:
        return None

    found_keys = []
    if search_type == 'relay_name':
        if search_value in mapping:
            found_keys.append(search_value)
    else:
        for key, value in mapping.items():
            if len(value) > search_index and value[search_index] == search_value:
                found_keys.append(key)

    if not found_keys:
        return None

    if return_type in ['english_name', 'relay_name']:
        for key in found_keys:
            if key.startswith('relay'):
                return key
        return found_keys[0] if found_keys else None
    else:
        target_key = found_keys[0]
        target_value = mapping[target_key]

        if return_type == 'function_detail':
            return target_value[0] if len(target_value) > 0 else None
        elif return_type == 'function_name':
            return target_value[1] if len(target_value) > 1 else None
        elif return_type == 'function_content':
            return target_value[2] if len(target_value) > 2 else None
        else:
            return None




