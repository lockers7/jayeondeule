# 농장/재배사 이름 조회
# --->
# 데이터베이스에서 농장명/재배사명을 조회
# Args:
# farm_id: 농장 ID
# house_id: 재배사 ID (선택)
# Returns:
# tuple[str, str]: (농장명, 재배사명) - 재배사명이 없으면 빈 문자열
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def get_farm_name(farm_id=None, house_id=None):
    if farm_id is None:
        return ("알수없는 농장", "")

    try:

        with db_session() as database:
            if house_id is None:
                result = database.fetch_one(
                    query=dbQry.GET_FARM_NAME,
                    vals=(farm_id, None)
                )
                if not result:
                    return (f"알수없는 농장코드: {farm_id}", "")
                return (result.get("farm_name", ""), "")

            result = database.fetch_one(
                query=dbQry.GET_FARM_HOUSE_INFO,
                vals=(farm_id, house_id)
            )
            if not result:
                return (
                    f"농장코드: {farm_id}",
                    f"알수없는 재배사코드: {house_id}"
                )
            return (result.get("farm_name", ""), result.get("hous_name", ""))

    except Exception as exc:
        logger.error(
            "농장/재배사 이름 조회 중 오류 - farm_id=%s, house_id=%s, err=%s",
            farm_id,
            house_id,
            exc
        )
        return (
            f"농장코드: {farm_id}" if farm_id is not None else "알수없는 농장",
            f"재배사코드: {house_id}" if house_id is not None else ""
        )



