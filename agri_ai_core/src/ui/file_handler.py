# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# Streamlit 파일 핸들러 모듈
# 파일 업로드, 다운로드, 미리보기 등 파일 관련 UI 기능을
# 처리합니다.
# --->
# handle_file_upload: 파일 업로드 UI 및 처리
# display_uploaded_files: 업로드된 파일 목록 표시 및 관리
# cleanup_uploaded_files: 업로드된 파일 모두 정리
# get_file_paths: 현재 업로드된 파일 경로 목록 반환
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
import os
import streamlit as stl
from datetime import datetime


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 업로드 디렉토리 설정
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
UPLOAD_DIR = os.path.join(os.path.dirname(__file__), "uploads")
if not os.path.exists(UPLOAD_DIR):
    os.makedirs(UPLOAD_DIR)


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 파일 업로드 처리
# --->
# 파일 업로드 UI 및 처리
# Returns:
# list: 업로드된 파일 목록
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def handle_file_upload():
    uploaded_files = stl.file_uploader(
        "파일 첨부 (CSV, Excel, 이미지 파일 등)",
        type=["csv", "xlsx", "xls", "jpg", "jpeg", "png", "pdf", "txt"],
        accept_multiple_files=True,
        key="file_upload"
    )

    if uploaded_files:
        for uploaded_file in uploaded_files:
            # 이미 업로드된 파일인지 확인
            if not any(file["name"] == uploaded_file.name for file in stl.session_state.uploaded_files):
                file_path = os.path.join(UPLOAD_DIR, uploaded_file.name)

                try:
                    with open(file_path, "wb") as f:
                        f.write(uploaded_file.getbuffer())

                    file_info = {
                        "name": uploaded_file.name,
                        "path": file_path,
                        "type": uploaded_file.type,
                        "size": uploaded_file.size,
                        "upload_time": datetime.now().strftime("%Y-%m-%d %H:%M:%S")
                    }
                    stl.session_state.uploaded_files.append(file_info)
                except Exception as e:
                    stl.error(f"파일 '{uploaded_file.name}' 업로드 중 오류 발생: {str(e)}")

    return stl.session_state.uploaded_files


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 업로드된 파일 목록 표시
# --->
# 업로드된 파일 목록 표시 및 관리
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def display_uploaded_files():
    if stl.session_state.uploaded_files:
        to_delete = None
        for idx, file_info in enumerate(stl.session_state.uploaded_files):
            stl.markdown("<div style='padding:6px 12px; margin:0; border-bottom:1px solid #e9ecef;'>", unsafe_allow_html=True)
            col1, col2, col3 = stl.columns([4, 2, 1])
            size_kb = file_info["size"] / 1024
            with col1:
                stl.markdown(f"<span style='color:#28a745; font-size:13px; line-height:1.3;'>{file_info['name']} ({size_kb:.1f} KB)</span>", unsafe_allow_html=True)
            with col2:
                stl.markdown(f"<span style='color:#6c757d; font-size:11px; line-height:1.3;'>{file_info['upload_time']}</span>", unsafe_allow_html=True)
            with col3:
                if stl.button("삭제", key=f"del_{idx}"):
                    to_delete = idx
            stl.markdown("</div>", unsafe_allow_html=True)

        # 삭제는 별도 처리하여 DOM 충돌 방지
        if to_delete is not None:
            try:
                file_info = stl.session_state.uploaded_files[to_delete]
                file_path = file_info["path"]

                # 파일 삭제
                if os.path.exists(file_path):
                    os.remove(file_path)

                # 리스트에서 제거
                stl.session_state.uploaded_files.pop(to_delete)
            except Exception as e:
                stl.error(f"파일 삭제 중 오류 발생: {str(e)}")


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 파일 정리
# --->
# 업로드된 파일 모두 정리
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def cleanup_uploaded_files():
    for file_info in stl.session_state.uploaded_files:
        try:
            if os.path.exists(file_info["path"]):
                os.remove(file_info["path"])
        except Exception:
            pass

    stl.session_state.uploaded_files = []


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 현재 업로드된 파일 경로 목록 반환
# --->
# Returns:
# list: 파일 경로 정보 목록
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def get_file_paths():
    return [
        {"filename": file["name"], "path": file["path"]}
        for file in stl.session_state.uploaded_files
    ]
