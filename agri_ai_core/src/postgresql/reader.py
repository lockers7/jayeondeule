# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 현재 생육단계 조회
# FARMHOUSE_M_INFO.crop_lvel + CODE_M_INFO(crop_lvel) JOIN으로 생육단계명 반환
#
# Args:
#     farm_id: 농장 ID
#     house_id: 재배사 ID
#
# Returns:
#     str: 생육단계 문자열 (발아기/생육기/수확기/휴지기) 또는 None
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def read_current_growth_stage(farm_id, house_id):
    with db_session() as database:
        try:
            result = database.fetch_one(
                query=dbQry.GET_CURRENT_CROP_LVEL,
                vals=(farm_id, int(house_id))
            )
            if result:
                return result.get("생육단계")
            return None
        except Exception as e:
            logger.warning(f"농장 {farm_id}, 재배사 {house_id}의 생육단계 조회 오류: {str(e)}")
            return None


