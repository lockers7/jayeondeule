# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 조회 시간 업데이트
# 재배사의 마지막 조회 시간 업데이트
#
# Args:
#     farm_id: 농장 ID
#     house_id: 재배사 ID
#     get_time: 조회 시간 (None이면 현재 시간)
#
# Returns:
#     bool: 성공 여부
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def update_last_get_time(farm_id, house_id, get_time=None):
    if get_time is None:
        get_time = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    with db_session() as database:
        try:
            result = database.execute_query(
                dbQry.SET_FARMHOUSE_INFO,
                vals=(get_time, farm_id, int(house_id))
            )
            return result
        except Exception as e:
            logger.warning(f"조회 시간 업데이트 오류 (farm_id={farm_id}, house_id={house_id}): {str(e)}")
            return False
