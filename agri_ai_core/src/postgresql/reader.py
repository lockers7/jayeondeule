from agri_ai_core.logs import setup_logger
from agri_ai_core.src.postgresql.connection import db_session
from agri_ai_core.src.postgresql import queries as dbQry

logger = setup_logger(__name__)


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 농장-재배사 목록 조회
# 모든 농장-재배사 목록 조회
#
# Returns:
#     list: 농장-재배사 목록
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def read_farm_house_list():
    with db_session() as database:
        try:
            farmhouses = database.fetch_all(query=dbQry.GET_FARM_HOUSE_LIST, vals=(), as_dict=True)
            return farmhouses
        except Exception as e:
            import traceback
            logger.error(f"농장-재배사 목록 조회 오류: {str(e)}")
            logger.error(f"스택 트레이스: {traceback.format_exc()}")
            return []


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# Units 데이터 조회
# 특정 농장/재배사의 Units 데이터 조회
#
# Args:
#     farm_id: 농장 ID
#     house_id: 재배사 ID
#
# Returns:
#     list: Units 데이터 목록
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def read_units_data(farm_id, house_id):
    with db_session() as database:
        try:
            units = database.fetch_all(
                query=dbQry.GET_UNITS_VALUE,
                vals=(farm_id, int(house_id)),
                as_dict=True
            )
            return units
        except Exception as e:
            logger.warning(f"농장 {farm_id}, 재배사 {house_id}의 Units 데이터 조회 오류: {str(e)}")
            return []


