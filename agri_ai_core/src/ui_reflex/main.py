# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# Reflex 메인 애플리케이션
# 앱 구조 및 페이지 정의
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
import reflex as rx
from .state import ChatState
from .components import chat_history, chat_input_area, file_upload_area, sidebar
from .styles import MAIN_CONTENT_STYLE, HEADER_STYLE


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 메인 페이지
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def index() -> rx.Component:
    """
    메인 페이지 렌더링

    Returns:
        rx.Component: 전체 페이지 레이아웃
    """
    return rx.hstack(
        # 왼쪽 사이드바
        sidebar(),

        # 오른쪽 메인 컨텐츠
        rx.box(
            # LLM 처리 중 표시 아이콘 (우측 상단)
            rx.cond(
                ChatState.is_loading,
                rx.box(
                    rx.text("🚴", class_name="running-bicycle"),
                    class_name="llm-running-indicator",
                ),
                rx.box(),
            ),

            # 헤더
            rx.box(
                rx.heading(
                    "🍄 자연들에 상황버섯 AI",
                    size="7",
                    color="#1B5E20",
                    margin="0",
                ),
                rx.text(
                    "스마트팜 관리 및 재배 상담 서비스",
                    font_size="13px",
                    color="#616161",
                    font_weight="700",
                    margin_top="4px",
                ),
                **HEADER_STYLE,
            ),

            # 채팅 히스토리
            chat_history(),

            # 입력 영역
            chat_input_area(),

            # 파일 업로드 영역 (입력창 아래)
            file_upload_area(),

            **MAIN_CONTENT_STYLE,
        ),

        spacing="0",
        width="100%",
        height="100vh",
    )


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 앱 생성 및 설정
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# "Built with Reflex" 푸터 제거를 위한 커스텀 스타일
custom_style = {
    "footer": {
        "display": "none",
    },
    "a[href*='reflex.dev']": {
        "display": "none !important",
    },
}

app = rx.App(
    style=custom_style,
    stylesheets=[
        "/custom.css",  # 커스텀 CSS로 Reflex 푸터 완전 제거
    ],
)
app.add_page(
    index,
    title="자연들에 상황버섯 AI",
    description="스마트팜 관리 및 재배 상담 서비스",
    on_load=ChatState.on_load,
)
