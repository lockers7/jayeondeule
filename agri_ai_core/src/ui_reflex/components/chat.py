# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# Reflex 채팅 컴포넌트
# 채팅 메시지 표시 및 히스토리 관리
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
import reflex as rx
from ..state import ChatState
from ..styles import CHAT_BUBBLE_USER, CHAT_BUBBLE_ASSISTANT, CHAT_CONTAINER_STYLE, FILE_ATTACHMENT_STYLE


# --------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 파일 첨부 표시 컴포넌트
# 파일 첨부 표시
# --------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def file_attachment(file) -> rx.Component:
    return rx.box(
        rx.hstack(
            rx.text("📎", margin_right="4px"),
            rx.text(
                f"{file.name} ({file.size / 1024:.1f} KB)",
                font_size="12px",
                color="#000000",
            ),
            spacing="1",
        ),
        **FILE_ATTACHMENT_STYLE,
    )


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 사용자 메시지 버블
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def user_message_bubble(message) -> rx.Component:
    return rx.box(
        rx.box(
            rx.markdown(
                message.content,
                class_name="chat-message-markdown",
                color="#000000",
                margin="0",
                white_space="pre-wrap",
                word_break="break-word",
                line_height="1.3",
            ),
            rx.cond(
                message.files,
                rx.box(
                    rx.foreach(message.files, file_attachment),
                ),
                rx.box(),
            ),
            **CHAT_BUBBLE_USER,
        ),
        display="flex",
        justify_content="flex-end",
        width="100%",
    )


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 어시스턴트 메시지 버블
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def assistant_message_bubble(message) -> rx.Component:
    return rx.box(
        rx.box(
            rx.markdown(
                message.content,
                class_name="chat-message-markdown",
                color="#000000",
                margin="0",
                white_space="pre-wrap",
                word_break="break-word",
                line_height="1.3",
            ),
            **CHAT_BUBBLE_ASSISTANT,
        ),
        display="flex",
        justify_content="flex-start",
        width="100%",
    )


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 채팅 버블 컴포넌트 (조건부 렌더링)
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def chat_bubble(message) -> rx.Component:
    return rx.cond(
        message.role == "user",
        user_message_bubble(message),
        assistant_message_bubble(message),
    )


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 채팅 히스토리 컴포넌트
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def chat_history() -> rx.Component:
    return rx.box(
        rx.cond(
            ChatState.messages,
            rx.foreach(
                ChatState.messages,
                chat_bubble
            ),
            rx.box(
                rx.text(
                    "💬 대화를 시작해보세요!",
                    color="#000000",
                    font_size="14px",
                    font_weight="700",
                    text_align="center",
                ),
                padding="40px",
            )
        ),
        **CHAT_CONTAINER_STYLE,
    )
