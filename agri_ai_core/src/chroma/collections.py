# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# ChromaDB 컬렉션 관리 모듈
# 농장, 문서, 학습 데이터 등 각종 컬렉션의 생성, 조회, 삭제 등
# 컬렉션 수준의 관리 기능을 제공합니다.
# --->
# farm_collection: 농장 메타데이터 컬렉션
# source_collection: 원본 센서/릴레이 데이터 컬렉션
# stats_collection: 통계 데이터 컬렉션
# optimal_collection: 최적 환경 조건 컬렉션
# learned_collection: LLM 학습 패턴 컬렉션
# setting_collection: 시스템 설정 컬렉션
# document_collection: 업로드된 문서 컬렉션
# job_status_collection: 작업 상태 컬렉션
# self_learning_collection: 자가학습 패턴 컬렉션
# learning_pattern_collection: 패턴 분석 결과 컬렉션
# get_all_collection_names: 모든 컬렉션 이름 목록 반환
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
from agri_ai_core.config import settings


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 컬렉션 이름 반환 함수들
# --->
# 농장 메타데이터 컬렉션
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def farm_collection():
    return settings.collections.farm or ''


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 원본 센서/릴레이 데이터 컬렉션
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def source_collection():
    return settings.collections.source or ''


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 통계 데이터 컬렉션
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def stats_collection():
    return settings.collections.stats or ''


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 최적 환경 조건 컬렉션
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def optimal_collection():
    return settings.collections.optimal or ''


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# LLM 학습 패턴 컬렉션
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def learned_collection():
    return settings.collections.learned or ''


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 시스템 설정 컬렉션
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def setting_collection():
    return settings.collections.setting or ''


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 업로드된 문서 컬렉션
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def document_collection():
    return settings.collections.docs_learned or ''


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 작업 상태 컬렉션
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def job_status_collection():
    return settings.collections.last_learned or ''


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 자가학습 패턴 컬렉션
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def self_learning_collection():
    return settings.collections.self_learned or ''


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 패턴 분석 결과 컬렉션
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def learning_pattern_collection():
    return settings.collections.pattern_learned or ''


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 모든 컬렉션 이름 목록
# --->
# 모든 컬렉션 이름 목록 반환
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def get_all_collection_names():
    return [
        ("farm_collection", farm_collection()),
        ("source_collection", source_collection()),
        ("stats_collection", stats_collection()),
        ("optimal_collection", optimal_collection()),
        ("learned_collection", learned_collection()),
        ("last_learned_date", job_status_collection()),
        ("setting_collection", setting_collection()),
        ("document_collection", document_collection()),
        ("self_learning_collection", self_learning_collection()),
        ("learning_pattern_collection", learning_pattern_collection())
    ]
