# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# FastAPI 서버 실행 모듈
# FastAPI 애플리케이션을 Uvicorn 서버로 실행하는
# 메인 엔트리포인트입니다.
# --->
# main: FastAPI 서버 시작
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
import traceback

import uvicorn

from agri_ai_core.log_utils.log_handlers import setup_logger
from agri_ai_core.api.main import create_app

logger = setup_logger(__name__)


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# FastAPI 서버 시작
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def main():
    logger.info("\n" * 2)
    logger.info("=" * 60)
    logger.info("AgriAI Core API 서버 시작")
    logger.info("=" * 60)

    try:
        app = create_app()
        server = uvicorn.Server(uvicorn.Config(
            app=app,
            host="0.0.0.0",
            port=8088,
            log_level="info",
        ))
        server.run()
    except KeyboardInterrupt:
        logger.info("사용자 중단 요청 (Ctrl+C)")
    except Exception as exc:
        logger.error(f"예기치 않은 오류 발생: {exc}")
        logger.error(traceback.format_exc())
        raise
    finally:
        logger.info("서비스 종료")


if __name__ == "__main__":
    main()
