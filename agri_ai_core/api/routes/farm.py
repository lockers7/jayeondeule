# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 농장 및 재배사 관리 API 엔드포인트 모듈
# 농장 정보 조회, 센서 상태 확인, 릴레이 제어, 작동 모드 변경 등
# 농장 운영에 필요한 모든 REST API를 제공합니다.
# --->
# [클래스] FarmStatusResponse: 농장 상태 응답 모델
# [클래스] RelayControlRequest: 릴레이 제어 요청 모델
# [클래스] RelayControlResponse: 릴레이 제어 응답 모델
# [클래스] OperationModeRequest: 작동 모드 변경 요청 모델
# get_default_farm_info: 기본 농장 정보 조회 엔드포인트
# get_farm_status: 농장 상태 조회 엔드포인트
# get_relay_status_endpoint: 릴레이 상태 조회 엔드포인트
# control_relay: 릴레이 제어 엔드포인트
# change_mode: 작동 모드 변경 엔드포인트
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
from typing import Optional, List
from fastapi import APIRouter, HTTPException, Query
from pydantic import BaseModel

from agri_ai_core.log_utils.log_handlers import setup_logger
from agri_ai_core.control.relay.relay_controller import (
    get_single_house_status,
    get_all_houses_status,
    change_operation_mode
)
from agri_ai_core.control.relay.relay_manager import (
    set_relay_value,
    get_relay_status
)
from agri_ai_core.database.postgres.connection import db_session
from agri_ai_core.database.postgres.queries import GET_ONE_FARM, GET_ONE_HOUSE

logger = setup_logger(__name__)

router = APIRouter()


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 요청/응답 모델
# --->
# 농장 상태 응답 모델
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class FarmStatusResponse(BaseModel):
    farm_id: str
    farm_name: Optional[str] = None
    house_id: Optional[str] = None
    house_name: Optional[str] = None
    operation_mode: Optional[str] = None
    record_datetime: Optional[str] = None
    indoor_temperature: Optional[float] = None
    indoor_humidity: Optional[float] = None
    co2: Optional[float] = None
    water_temperature: Optional[float] = None
    light_level: Optional[float] = None
    outdoor_temperature: Optional[float] = None
    outdoor_humidity: Optional[float] = None


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 릴레이 제어 요청 모델
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class RelayControlRequest(BaseModel):
    farm_id: str
    house_id: str
    relay_settings: dict


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 릴레이 제어 응답 모델
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class RelayControlResponse(BaseModel):
    success: bool
    message: str
    farm_id: Optional[str] = None
    house_id: Optional[str] = None
    settings: Optional[dict] = None


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 작동 모드 변경 요청 모델
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
class OperationModeRequest(BaseModel):
    farm_id: str
    house_id: Optional[str] = None
    mode: str  # "manual" or "auto"


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 기본 농장 정보 조회
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@router.get("/get_default_farm_info")
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 기본 농장 정보 조회 엔드포인트
# --->
# Returns:
# dict: 기본 농장 및 재배사 정보
# - farm_id: 농장 ID
# - farm_name: 농장명
# - house_id: 재배사 ID
# - house_name: 재배사명
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
async def get_default_farm_info():
    try:
        logger.info("기본 농장 정보 조회 요청")

        with db_session() as database:
            # 첫 번째 농장 조회
            farm = database.fetch_one(GET_ONE_FARM)
            if not farm:
                raise HTTPException(
                    status_code=404,
                    detail="등록된 농장이 없습니다."
                )

            farm_id = farm.get("farm_id")
            farm_name = farm.get("farm_name", "기본농장")

            # 첫 번째 재배사 조회
            house = database.fetch_one(GET_ONE_HOUSE, (farm_id,))
            if not house:
                # 재배사가 없을 경우 기본값 사용
                logger.warning(f"농장 {farm_id}에 재배사가 없습니다. 기본값 사용")
                house_id = 1
                house_name = "기본재배사"
            else:
                house_id = house.get("hous_id")
                house_name = house.get("hous_name", "기본재배사")

            result = {
                "farm_id": str(farm_id),
                "farm_name": farm_name,
                "house_id": str(house_id),
                "house_name": house_name
            }

            logger.info(f"기본 농장 정보 조회 성공: {result}")
            return result

    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"기본 농장 정보 조회 중 오류: {e}")
        # 오류 발생 시 기본값 반환
        return {
            "farm_id": "1",
            "farm_name": "기본농장",
            "house_id": "1",
            "house_name": "기본재배사"
        }


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 농장 상태 조회
# --->
# 농장 상태 조회 엔드포인트
# Args:
#     farm_id: 농장 ID
#     house_id: 재배사 ID (선택)
# Returns:
#     List[FarmStatusResponse]: 농장 상태 목록
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@router.get("/farm/{farm_id}/status", response_model=List[FarmStatusResponse])
async def get_farm_status(
    farm_id: str,
    house_id: Optional[str] = Query(None, description="재배사 ID")
):
    try:
        logger.info(f"농장 상태 조회: farm_id={farm_id}, house_id={house_id}")

        if house_id:
            # 특정 재배사 조회
            status = get_single_house_status(farm_id, house_id)
            if status:
                return [FarmStatusResponse(**status)]
            else:
                raise HTTPException(
                    status_code=404,
                    detail=f"농장 {farm_id}, 재배사 {house_id}의 데이터를 찾을 수 없습니다."
                )
        else:
            # 전체 재배사 조회
            statuses = get_all_houses_status(farm_id)
            if statuses:
                return [FarmStatusResponse(**s) for s in statuses]
            else:
                raise HTTPException(
                    status_code=404,
                    detail=f"농장 {farm_id}의 데이터를 찾을 수 없습니다."
                )

    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"농장 상태 조회 중 오류: {e}")
        raise HTTPException(
            status_code=500,
            detail=f"농장 상태 조회 중 오류가 발생했습니다: {str(e)}"
        )


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 릴레이 상태 조회
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@router.get("/farm/{farm_id}/house/{house_id}/relay")
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 릴레이 상태 조회 엔드포인트
# --->
# Args:
# farm_id: 농장 ID
# house_id: 재배사 ID
# Returns:
# dict: 릴레이 상태
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
async def get_relay_status_endpoint(farm_id: str, house_id: str):
    try:
        logger.info(f"릴레이 상태 조회: farm_id={farm_id}, house_id={house_id}")

        status = get_relay_status(farm_id, house_id)
        if status:
            return status
        else:
            raise HTTPException(
                status_code=404,
                detail=f"농장 {farm_id}, 재배사 {house_id}의 릴레이 상태를 찾을 수 없습니다."
            )

    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"릴레이 상태 조회 중 오류: {e}")
        raise HTTPException(
            status_code=500,
            detail=f"릴레이 상태 조회 중 오류가 발생했습니다: {str(e)}"
        )


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 릴레이 제어
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@router.post("/farm/relay/control", response_model=RelayControlResponse)
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 릴레이 제어 엔드포인트
# --->
# Args:
# request: 릴레이 제어 요청
# Returns:
# RelayControlResponse: 릴레이 제어 응답
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
async def control_relay(request: RelayControlRequest):
    try:
        logger.info(f"릴레이 제어: farm_id={request.farm_id}, house_id={request.house_id}")

        result = set_relay_value(
            farm_id=request.farm_id,
            house_id=request.house_id,
            relay_settings=request.relay_settings
        )

        return RelayControlResponse(**result)

    except Exception as e:
        logger.error(f"릴레이 제어 중 오류: {e}")
        raise HTTPException(
            status_code=500,
            detail=f"릴레이 제어 중 오류가 발생했습니다: {str(e)}"
        )


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 작동 모드 변경
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@router.post("/farm/mode", response_model=RelayControlResponse)
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 작동 모드 변경 엔드포인트
# --->
# Args:
# request: 작동 모드 변경 요청
# Returns:
# RelayControlResponse: 작동 모드 변경 응답
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
async def change_mode(request: OperationModeRequest):
    try:
        logger.info(f"작동 모드 변경: farm_id={request.farm_id}, house_id={request.house_id}, mode={request.mode}")

        result = change_operation_mode(
            farm_id=request.farm_id,
            house_id=request.house_id,
            mode=request.mode
        )

        return RelayControlResponse(
            success=result.get("success", False),
            message=result.get("message", ""),
            farm_id=request.farm_id,
            house_id=request.house_id
        )

    except Exception as e:
        logger.error(f"작동 모드 변경 중 오류: {e}")
        raise HTTPException(
            status_code=500,
            detail=f"작동 모드 변경 중 오류가 발생했습니다: {str(e)}"
        )
