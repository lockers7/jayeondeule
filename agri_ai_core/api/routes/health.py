# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 서버 상태 체크 엔드포인트 모듈
# API 서버의 헬스체크 및 시스템 상태를 확인하는 기능을 제공합니다.
# --->
# health_check: 기본 헬스체크 엔드포인트
# detailed_health_check: 상세 헬스체크 엔드포인트
# readiness_check: 준비 상태 확인 엔드포인트
# liveness_check: 활성 상태 확인 엔드포인트
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
from datetime import datetime
from fastapi import APIRouter, HTTPException

from agri_ai_core.log_utils.log_handlers import setup_logger
from agri_ai_core.database.chromadb.client import heartbeat, get_version

logger = setup_logger(__name__)

router = APIRouter()


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 기본 헬스체크
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@router.get("/health")
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 기본 헬스체크 엔드포인트
# --->
# Returns:
# dict: 시스템 상태
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
async def health_check():
    return {
        "status": "healthy",
        "timestamp": datetime.now().isoformat(),
        "service": "AgriAI Core API"
    }


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 상세 헬스체크
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@router.get("/health/detailed")
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 상세 헬스체크 엔드포인트
# --->
# Returns:
# dict: 상세 시스템 상태
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
async def detailed_health_check():
    status = {
        "status": "healthy",
        "timestamp": datetime.now().isoformat(),
        "service": "AgriAI Core API",
        "components": {}
    }

    # ChromaDB 상태 확인
    try:
        chroma_status = heartbeat()
        if "error" in chroma_status:
            status["components"]["chromadb"] = {
                "status": "unhealthy",
                "error": chroma_status.get("error")
            }
        else:
            version = get_version()
            status["components"]["chromadb"] = {
                "status": "healthy",
                "version": version
            }
    except Exception as e:
        status["components"]["chromadb"] = {
            "status": "unhealthy",
            "error": str(e)
        }

    # 전체 상태 결정
    unhealthy_components = [
        name for name, info in status["components"].items()
        if info.get("status") == "unhealthy"
    ]

    if unhealthy_components:
        status["status"] = "degraded"
        status["unhealthy_components"] = unhealthy_components

    return status


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 준비 상태 확인
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@router.get("/ready")
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 준비 상태 확인 엔드포인트
# --->
# Returns:
# dict: 준비 상태
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
async def readiness_check():
    try:
        # ChromaDB 연결 확인
        chroma_status = heartbeat()
        if "error" in chroma_status:
            raise HTTPException(
                status_code=503,
                detail=f"ChromaDB not ready: {chroma_status.get('error')}"
            )

        return {
            "ready": True,
            "timestamp": datetime.now().isoformat()
        }

    except HTTPException:
        raise
    except Exception as e:
        raise HTTPException(
            status_code=503,
            detail=f"Service not ready: {str(e)}"
        )


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 활성 상태 확인
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
@router.get("/live")
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 활성 상태 확인 엔드포인트
# --->
# Returns:
# dict: 활성 상태
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
async def liveness_check():
    return {
        "live": True,
        "timestamp": datetime.now().isoformat()
    }
