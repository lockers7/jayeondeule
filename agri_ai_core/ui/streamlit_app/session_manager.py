# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# Streamlit 세션 관리 모듈
# 사용자 세션 상태, 대화 히스토리, 선택된 농장 정보 등을
# Streamlit 세션에서 관리합니다.
# --->
# initialize_session_state: Streamlit 세션 상태 초기화
# get_default_farm_info: DB에서 직접 기본 농장 정보 조회
# add_user_message: 사용자 메시지 추가
# add_assistant_message: 어시스턴트 메시지 추가
# clear_messages: 메시지 기록 초기화
# get_messages: 메시지 기록 반환
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
import streamlit as stl
from datetime import datetime

from agri_ai_core.log_utils.log_handlers import setup_logger
from agri_ai_core.database.postgres.connection import db_session
from agri_ai_core.database.postgres.queries import GET_ONE_FARM, GET_ONE_HOUSE

logger = setup_logger(__name__)


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 세션 상태 초기화
# --->
# Streamlit 세션 상태 초기화
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def initialize_session_state():
    if "messages" not in stl.session_state:
        stl.session_state.messages = []

    if "uploaded_files" not in stl.session_state:
        stl.session_state.uploaded_files = []

    if "farm_id" not in stl.session_state:
        stl.session_state.farm_id = 1

    if "house_id" not in stl.session_state:
        stl.session_state.house_id = 1

    if "farm_name" not in stl.session_state:
        stl.session_state.farm_name = ""

    if "house_name" not in stl.session_state:
        stl.session_state.house_name = ""

    if "weather_city" not in stl.session_state:
        stl.session_state.weather_city = "정읍"

    if "user_location_detected" not in stl.session_state:
        stl.session_state.user_location_detected = False

    if "ip_location_detected" not in stl.session_state:
        stl.session_state.ip_location_detected = False

    if "client_location_applied" not in stl.session_state:
        stl.session_state.client_location_applied = False


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 기본 농장 정보 조회
# --->
# DB에서 직접 기본 농장 정보 조회
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def get_default_farm_info():
    if stl.session_state.farm_name and stl.session_state.house_name:
        return

    try:
        with db_session() as database:
            farm = database.fetch_one(GET_ONE_FARM)
            if not farm:
                logger.warning("등록된 농장이 없습니다. 기본값을 사용합니다.")
                _set_default_farm()
                return

            farm_id = farm.get("farm_id")
            farm_name = farm.get("farm_name", "기본농장")

            house = database.fetch_one(GET_ONE_HOUSE, (farm_id,))
            if not house:
                logger.warning(f"농장 {farm_id}에 재배사가 없습니다. 기본값 사용")
                house_id = 1
                house_name = "기본재배사"
            else:
                house_id = house.get("hous_id")
                house_name = house.get("hous_name", "기본재배사")

            stl.session_state.farm_id = str(farm_id)
            stl.session_state.house_id = str(house_id)
            stl.session_state.farm_name = farm_name
            stl.session_state.house_name = house_name
            logger.info(f"기본 농장 정보 로드: farm={farm_name}, house={house_name}")

    except Exception as e:
        logger.error(f"기본 농장 정보 조회 중 오류: {e}")
        _set_default_farm()


def _set_default_farm():
    stl.session_state.farm_id = 1
    stl.session_state.house_id = 1
    stl.session_state.farm_name = "기본농장"
    stl.session_state.house_name = "기본재배사"


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 메시지 기록 관리
# --->
# 사용자 메시지 추가
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def add_user_message(content: str, files: list = None):
    user_message = {
        "role": "user",
        "content": content,
        "files": files or [],
        "timestamp": datetime.now().isoformat()
    }
    stl.session_state.messages.append(user_message)
    return user_message


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 어시스턴트 메시지 추가
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def add_assistant_message(content: str):
    assistant_message = {
        "role": "assistant",
        "content": content,
        "timestamp": datetime.now().isoformat()
    }
    stl.session_state.messages.append(assistant_message)
    return assistant_message


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 메시지 기록 초기화
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def clear_messages():
    stl.session_state.messages = []


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 메시지 기록 반환
# --->
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def get_messages():
    return stl.session_state.messages
