# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# IP 기반 위치 자동 설정
# --->
# 세션에 IP 기반 위치를 설정
# Args:
# force: 강제 갱신 여부
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def ensure_ip_location_set(force: bool = False):
    try:
        # 클라이언트 측 위치가 이미 적용된 경우 덮어쓰지 않음
        if stl.session_state.get('client_location_applied', False) and not force:
            return

        # IP 위치가 이미 감지된 경우 스킵
        if stl.session_state.get('ip_location_detected', False) and not force:
            return

        # 기본값 설정 (실제 구현에서는 IP 기반 위치 API 호출)
        stl.session_state.weather_city = "정읍"
        stl.session_state.ip_location_detected = True
        stl.session_state.ip_detected_at = datetime.now().isoformat()

    except Exception as e:
        try:
            stl.warning(f"IP 기반 위치 감지 실패: {e}")
        except Exception:
            pass


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 브라우저 위치 감지 스크립트
# --->
# JavaScript로 사용자의 실제 위치 감지
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def auto_detect_user_location():
    if stl.session_state.get('location_detected_flag', False):
        return

    stl.session_state.location_detected_flag = True

    # 도시 좌표 데이터 생성
    cities_js = ",\n".join([
        f"{{name: '{name}', lat: {info['lat']}, lon: {info['lon']}}}"
        for name, info in KOREAN_CITIES.items()
    ])

    location_script = f"""
    <script>
    if (navigator.geolocation && !sessionStorage.getItem('location_checked')) {{
        sessionStorage.setItem('location_checked', 'true');

        navigator.geolocation.getCurrentPosition(
            function(position) {{
                const lat = position.coords.latitude;
                const lon = position.coords.longitude;

                const cities = [
                    {cities_js}
                ];

                let minDistance = Infinity;
                let closestCity = '서울';

                cities.forEach(city => {{
                    const distance = Math.sqrt(
                        Math.pow(lat - city.lat, 2) + Math.pow(lon - city.lon, 2)
                    );
                    if (distance < minDistance) {{
                        minDistance = distance;
                        closestCity = city.name;
                    }}
                }});

                // URL 파라미터로 전달
                const url = new URL(window.location);
                url.searchParams.set('auto_detected_city', closestCity);
                sessionStorage.setItem('client_location_applied', 'true');
                window.history.replaceState({{}}, '', url);
                window.location.reload();
            }},
            function(error) {{
                console.log('위치 권한 거부 또는 오류');
            }}
        );
    }}
    </script>
    """

    components.html(location_script, height=0)


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 위치 정보 처리
# --->
# 쿼리 파라미터에서 위치 정보 처리
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def process_location_from_params():
    query_params = stl.query_params
    auto_detected_city = query_params.get("auto_detected_city")

    if auto_detected_city:
        stl.session_state.weather_city = auto_detected_city
        stl.session_state.user_location_detected = True
        stl.session_state.client_location_applied = True
        stl.query_params.clear()
        return True

    return False


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 사용 가능한 도시 목록 반환
# --->
# Returns:
# list: 도시 이름 목록
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def get_available_cities():
    return sorted(KOREAN_CITIES.keys())


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 한국어 도시명의 영어명 반환
# --->
# Args:
# korean_name: 한국어 도시명
# Returns:
# str: 영어 도시명
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def get_city_english_name(korean_name: str) -> str:
    city_info = KOREAN_CITIES.get(korean_name)
    return city_info['english'] if city_info else korean_name


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 현재 설정된 날씨 도시 반환
# --->
# Returns:
# str: 도시명
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def get_current_weather_city():
    return stl.session_state.get('weather_city', '정읍')


# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
# 날씨 도시 설정
# --->
# Args:
# city: 도시명
# ------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------
def set_weather_city(city: str):
    stl.session_state.weather_city = city
    stl.session_state.user_location_detected = True
